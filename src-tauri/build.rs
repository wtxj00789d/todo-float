fn main() {
    let out_dir = std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is set"));
    let icon_path = out_dir.join("todo-float.ico");
    std::fs::write(&icon_path, TRANSPARENT_ICO).expect("write generated app icon");
    let icon_path_json = icon_path.to_string_lossy().replace('\\', "\\\\");
    println!("cargo:rustc-env=TAURI_CONFIG={{\"bundle\":{{\"icon\":[\"{icon_path_json}\"]}}}}");

    let windows = tauri_build::WindowsAttributes::new().window_icon_path(icon_path);
    let attributes = tauri_build::Attributes::new().windows_attributes(windows);
    tauri_build::try_build(attributes).expect("failed to run tauri build script");
}

